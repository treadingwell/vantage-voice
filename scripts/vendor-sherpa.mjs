// Regenerates src/vendor/sherpa/ from the pinned sherpa-onnx npm package.
//
// The npm build targets Node: its Emscripten loader hard-requires Node's filesystem
// (NODERAWFS) and "path" module. Two small patches make the same WASM run in a browser
// Web Worker with the default in-memory filesystem. The JS wrappers are re-exported as
// ES modules so each keeps its own scope (asr.js and tts.js both declare freeConfig).
//
// Usage: node scripts/vendor-sherpa.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = join(root, 'node_modules', 'sherpa-onnx');
const outDir = join(root, 'src', 'vendor', 'sherpa');
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;

const header = `// Generated by scripts/vendor-sherpa.mjs from sherpa-onnx@${version} (Apache-2.0). Do not edit.\n`;

function replaceOnce(source, from, to) {
  const parts = source.split(from);
  if (parts.length !== 2) {
    throw new Error(`Expected exactly one match for patch: ${from.slice(0, 60)}...`);
  }
  return parts.join(to);
}

// Minimal POSIX path module standing in for Node's "path" in the browser
const browserPath = `
const __browserPath = (() => {
  const normalizeArray = (parts, allowAboveRoot) => {
    const out = [];
    for (const p of parts) {
      if (!p || p === '.') continue;
      if (p === '..') {
        if (out.length && out[out.length - 1] !== '..') out.pop();
        else if (allowAboveRoot) out.push('..');
      } else out.push(p);
    }
    return out;
  };
  const isAbsolute = (p) => p.charAt(0) === '/';
  const normalize = (p) => {
    const abs = isAbsolute(p);
    const trailing = p.slice(-1) === '/';
    let s = normalizeArray(p.split('/'), !abs).join('/');
    if (!s && !abs) s = '.';
    if (s && trailing) s += '/';
    return (abs ? '/' : '') + s;
  };
  const dirname = (p) => {
    if (!p) return '.';
    const s = p.replace(/\\/+$/, '');
    const i = s.lastIndexOf('/');
    if (i === -1) return '.';
    if (i === 0) return '/';
    return s.slice(0, i);
  };
  const basename = (p) => {
    if (p === '/') return '/';
    const s = p.replace(/\\/+$/, '');
    return s.slice(s.lastIndexOf('/') + 1);
  };
  const join = (...parts) => normalize(parts.filter(Boolean).join('/'));
  const resolve = (...paths) => {
    let resolved = '';
    let abs = false;
    for (let i = paths.length - 1; i >= 0 && !abs; i--) {
      const p = paths[i];
      if (typeof p !== 'string' || !p) continue;
      resolved = p + '/' + resolved;
      abs = isAbsolute(p);
    }
    resolved = normalizeArray(resolved.split('/'), !abs).join('/');
    return (abs ? '/' : '') + resolved || '.';
  };
  const relative = (from, to) => {
    const f = resolve(from).split('/').filter(Boolean);
    const t = resolve(to).split('/').filter(Boolean);
    let i = 0;
    while (i < f.length && i < t.length && f[i] === t[i]) i++;
    return [...Array(f.length - i).fill('..'), ...t.slice(i)].join('/');
  };
  const posix = { isAbsolute, normalize, dirname, basename, join, resolve, relative };
  return { ...posix, posix };
})();
`;

let glue = readFileSync(join(pkgDir, 'sherpa-onnx-wasm-nodejs.js'), 'utf8');
// 1. Only swap in Node's raw filesystem when actually running under Node
glue = replaceOnce(
  glue,
  'if(!ENVIRONMENT_IS_NODE){throw new Error("NODERAWFS is currently only supported on Node.js environment.")}',
  ''
);
glue = replaceOnce(
  glue,
  'var VFS={...FS};for(var _key in NODERAWFS){FS[_key]=_wrapNodeError(NODERAWFS[_key])}',
  'var VFS={...FS};if(ENVIRONMENT_IS_NODE){for(var _key in NODERAWFS){FS[_key]=_wrapNodeError(NODERAWFS[_key])}}'
);
// 2. Use the POSIX shim instead of require("path") outside Node
glue = replaceOnce(
  glue,
  'var nodePath=require("path");',
  'var nodePath=ENVIRONMENT_IS_NODE?require("path"):__browserPath;'
);

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'sherpa-glue.js'), `${header}/* eslint-disable */\n${browserPath}\n${glue}\nexport default Module;\n`);
writeFileSync(
  join(outDir, 'sherpa-tts.js'),
  `${header}/* eslint-disable */\n${readFileSync(join(pkgDir, 'sherpa-onnx-tts.js'), 'utf8')}\nexport { createOfflineTts };\n`
);
writeFileSync(
  join(outDir, 'sherpa-asr.js'),
  `${header}/* eslint-disable */\n${readFileSync(join(pkgDir, 'sherpa-onnx-asr.js'), 'utf8')}\nexport { createOnlineRecognizer };\n`
);

console.log(`Vendored sherpa-onnx@${version} into ${outDir}`);
